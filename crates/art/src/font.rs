fn glyph(ch: char) -> &'static str {
    GLYPHS.iter().find(|(k, _)| *k == ch).or_else(|| GLYPHS.iter().find(|(k, _)| *k == '?')).map(|(_, g)| *g).unwrap()
}

pub fn text_width(text: &str, spacing: i32) -> i32 {
    let n = text.chars().count() as i32;
    if n == 0 { 0 } else { n * (3 + spacing) - spacing }
}

pub fn draw_text(c: &mut Canvas, text: &str, x: i32, y: i32, color: impl IntoColor, spacing: i32) {
    let col = color.rgba();
    let mut cx = x;
    for raw in text.to_uppercase().chars() {
        for (ry, row) in glyph(raw).split('|').enumerate() {
            for (rx, ch) in row.chars().enumerate() {
                if ch == '#' {
                    c.blend(cx + rx as i32, y + ry as i32, col);
                }
            }
        }
        cx += 3 + spacing;
    }
}
