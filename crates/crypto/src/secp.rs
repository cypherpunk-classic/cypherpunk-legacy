//! A thin, readable layer over RustCrypto's `k256` (secp256k1).
//!
//! The game shows players the actual group elements and scalars, so this
//! module names things the way the BIPs do: G, n, x-only keys, lift_x, tagged
//! hashes. Scalars are passed around as [`Big`] integers (like the formulas on
//! screen) and converted to `k256::Scalar` only to multiply points.

use std::sync::LazyLock;

use k256::elliptic_curve::group::GroupEncoding;
use k256::elliptic_curve::point::{AffineCoordinates, DecompressPoint};
use k256::elliptic_curve::PrimeField;
use k256::{AffinePoint, FieldBytes, Scalar};
use num_traits::Zero;
use sha2::{Digest, Sha256};

use crate::bytes::{Big, big_to_bytes, bytes_to_big, from_hex, modulo, mod_inv, to_hex};

/// A point on secp256k1 (projective coordinates; the identity is "O").
pub type Pt = k256::ProjectivePoint;

/// Order of the group generated by G.
pub static N: LazyLock<Big> = LazyLock::new(|| {
    bytes_to_big(&from_hex("FFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141").unwrap())
});

/// Field prime of the curve y^2 = x^3 + 7.
pub static P_FIELD: LazyLock<Big> = LazyLock::new(|| {
    bytes_to_big(&from_hex("FFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEFFFFFC2F").unwrap())
});

pub fn n() -> &'static Big {
    &N
}

pub fn g() -> Pt {
    Pt::GENERATOR
}

pub fn infinity() -> Pt {
    Pt::IDENTITY
}

pub fn mod_n(a: &Big) -> Big {
    modulo(a, &N)
}

pub fn inv_n(a: &Big) -> Big {
    mod_inv(a, &N).expect("not invertible mod n")
}

pub fn to_scalar(k: &Big) -> Scalar {
    let bytes: [u8; 32] = big_to_bytes(&mod_n(k), 32).try_into().unwrap();
    Option::from(Scalar::from_repr(FieldBytes::from(bytes))).expect("reduced scalar")
}

pub fn scalar_to_big(s: &Scalar) -> Big {
    bytes_to_big(&s.to_repr())
}

/// k*G
pub fn mul(k: &Big) -> Pt {
    let s = to_scalar(k);
    if bool::from(s.is_zero()) { Pt::IDENTITY } else { Pt::GENERATOR * s }
}

/// k*P
pub fn mul_pt(k: &Big, p: &Pt) -> Pt {
    *p * to_scalar(k)
}

pub fn is_infinity(p: &Pt) -> bool {
    p == &Pt::IDENTITY
}

fn affine(p: &Pt) -> AffinePoint {
    p.to_affine()
}

pub fn has_even_y(p: &Pt) -> bool {
    !bool::from(affine(p).y_is_odd())
}

/// 32-byte x coordinate, the BIP-340 "x-only" public key encoding.
pub fn x_only(p: &Pt) -> [u8; 32] {
    affine(p).x().into()
}

pub fn x_only_hex(p: &Pt) -> String {
    to_hex(&x_only(p))
}

pub fn x_big(p: &Pt) -> Big {
    bytes_to_big(&x_only(p))
}

pub fn y_big(p: &Pt) -> Big {
    bytes_to_big(&affine(p).y())
}

/// 33-byte compressed SEC1 encoding (used by BIP-327 KeyAgg and BIP-32).
pub fn compressed(p: &Pt) -> [u8; 33] {
    let repr = affine(p).to_bytes();
    let mut out = [0u8; 33];
    out.copy_from_slice(repr.as_slice());
    out
}

/// BIP-340 lift_x: the unique point with this x coordinate and even y.
pub fn lift_x(x: &[u8]) -> Option<Pt> {
    let bytes: [u8; 32] = x.try_into().ok()?;
    let p: Option<AffinePoint> = AffinePoint::decompress(&FieldBytes::from(bytes), 0u8.into()).into();
    p.map(Pt::from)
}

/// Decode a 32-byte x-only key or a 33-byte compressed key.
pub fn point_from_bytes(b: &[u8]) -> Option<Pt> {
    match b.len() {
        32 => lift_x(b),
        33 => {
            let mut repr = <AffinePoint as GroupEncoding>::Repr::default();
            repr.copy_from_slice(b);
            let p: Option<AffinePoint> = AffinePoint::from_bytes(&repr).into();
            p.filter(|p| p != &AffinePoint::IDENTITY).map(Pt::from)
        }
        _ => None,
    }
}

pub fn point_from_hex(h: &str) -> Option<Pt> {
    point_from_bytes(&from_hex(h).ok()?)
}

/// hash_tag(x) = SHA256(SHA256(tag) || SHA256(tag) || x), the BIP-340 tagged hash.
pub fn tagged_hash(tag: &str, msgs: &[&[u8]]) -> [u8; 32] {
    let th = Sha256::digest(tag.as_bytes());
    let mut h = Sha256::new();
    h.update(th);
    h.update(th);
    for m in msgs {
        h.update(m);
    }
    h.finalize().into()
}

pub fn sha256(data: &[u8]) -> [u8; 32] {
    Sha256::digest(data).into()
}

pub fn scalar_bytes(k: &Big) -> [u8; 32] {
    big_to_bytes(&mod_n(k), 32).try_into().unwrap()
}

pub fn scalar_to_hex(k: &Big) -> String {
    to_hex(&scalar_bytes(k))
}

pub fn point_label(p: &Pt) -> String {
    if is_infinity(p) {
        return "O (point at infinity)".into();
    }
    format!("({}, {} y)", x_only_hex(p), if has_even_y(p) { "even" } else { "odd" })
}

/// Is this integer a valid non-zero scalar?
pub fn is_scalar(k: &Big) -> bool {
    !k.is_zero() && k > &Big::zero() && k < &N
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::bytes::big;

    #[test]
    fn basics() {
        assert_eq!(
            x_only_hex(&g()),
            "79be667ef9dcbbac55a06295ce870b07029bfcdb2dce28d959f2815b16f81798"
        );
        assert!(has_even_y(&g()));
        let p = mul(&big(3));
        assert_eq!(p, g() + g() + g());
        assert_eq!(lift_x(&x_only(&p)).unwrap(), if has_even_y(&p) { p } else { -p });
        assert_eq!(point_from_bytes(&compressed(&p)).unwrap(), p);
        assert!(is_infinity(&mul(&N.clone())));
        assert_eq!(mod_n(&(inv_n(&big(5)) * big(5))), big(1));
    }
}
