//! Epilogue. The Archive, once public and signed, cannot be un-published. You
//! sign a release statement with your inherited key (BIP-340), bind it to the
//! Archive's hash, and broadcast it to every node in Cryptopolis. Warden's
//! whole power was keeping things locked; a signature everyone can verify ends
//! it.

use std::rc::Rc;

use cpl_crypto::aead::sha256_hex;
use cpl_crypto::bip340::{sign, verify};
use cpl_crypto::bytes::to_hex;
use cpl_crypto::drbg::random_bytes;
use egui::{Color32, CornerRadius, Margin, RichText, Stroke};

use crate::puzzle::{Host, Puzzle};
use crate::ui::theme::{self, CYAN, GREEN, LINE, mono};
use crate::ui::widgets::{Kind, Tone, button, card, hex_box, lede, note};
use crate::world::World;

pub const MANIFESTO: &str = "Privacy is necessary for an open society in the electronic age. Privacy is not secrecy. A private matter is something one doesn't want the whole world to know, but a secret matter is something one doesn't want anybody to know. Privacy is the power to selectively reveal oneself to the world.

We cannot expect governments, corporations, or other large, faceless organizations to grant us privacy out of their beneficence. We must defend our own privacy if we expect to have any.

Cypherpunks write code. We know that someone has to write software to defend privacy, and we're going to write it.";

pub struct Broadcast {
    world: Rc<World>,
    statement: String,
    signature: Option<(String, bool)>,
}

impl Broadcast {
    pub fn new(world: Rc<World>) -> Self {
        let archive_hash = sha256_hex(format!("{MANIFESTO}|archive|{}", world.seed_hex()).as_bytes());
        let statement = format!("CYPHERPUNK LEGACY — PUBLIC RELEASE\nReleased by: {}\nArchive SHA-256: {archive_hash}\n\n{MANIFESTO}", world.handle());
        Self { world, statement, signature: None }
    }

    fn sign(&mut self, host: &mut Host) {
        if self.signature.is_some() {
            return;
        }
        let id = self.world.identity();
        let sig = sign(self.statement.as_bytes(), &id.x, Some(random_bytes::<32>()));
        let ok = verify(&sig, self.statement.as_bytes(), &id.xonly);
        self.signature = Some((sig.hex(), ok));
        host.sfx("confirm");
        host.status("Signed. Now broadcast it.", Tone::Ok);
    }

    fn broadcast(&mut self, host: &mut Host) {
        if host.solved() || self.signature.is_none() {
            return;
        }
        host.sfx("success");
        host.solve("Broadcast complete. The manifesto and the Archive are public, signed, and permanent. There is no key that locks this again.");
    }

    fn certificate(&self) -> Option<String> {
        let (sig, _) = self.signature.as_ref()?;
        Some(format!(
            "{}\n\n---\nSIGNATURE (BIP-340 Schnorr, secp256k1):\n{sig}\n\nPUBLIC KEY (x-only): {}\n\nVerify: this signature is valid for the message above under the public key, forever.\nGenerated by Cypherpunk Legacy.",
            self.statement,
            to_hex(&self.world.identity().xonly)
        ))
    }
}

impl Puzzle for Broadcast {
    fn id(&self) -> &'static str {
        "end.broadcast"
    }

    fn title(&self) -> &str {
        "LEGACY BROADCAST"
    }

    fn subtitle(&self) -> Option<&str> {
        Some("sign · bind · publish")
    }

    fn accent(&self) -> Color32 {
        CYAN
    }

    fn closable(&self) -> bool {
        false
    }

    fn open(&mut self, host: &mut Host) {
        host.status("Sign the release.", Tone::Info);
    }

    fn ui(&mut self, ui: &mut egui::Ui, host: &mut Host) {
        lede(ui, "This is the last key you will turn tonight. The Archive is open; the Directorate wants it sealed again. But a signed, published document cannot be recalled. Sign your grandfather's manifesto with the key he left you, bind it to the Archive, and broadcast it to every node. After that, it is everyone's.");
        card(ui, Some("Release statement"), None, |ui| {
            egui::Frame::NONE.fill(theme::rgb(0x070b16)).stroke(Stroke::new(1.0, LINE)).corner_radius(CornerRadius::same(3)).inner_margin(Margin::same(8)).show(ui, |ui| {
                egui::ScrollArea::vertical().id_salt("bc-statement").max_height(200.0).auto_shrink([false, true]).show(ui, |ui| {
                    ui.add(egui::Label::new(RichText::new(&self.statement).font(mono(12.0)).color(theme::rgb(0xbff8ff))).wrap());
                });
            });
        });
        let mut act: Option<u8> = None;
        card(ui, Some("Sign and broadcast"), None, |ui| {
            hex_box(ui, &to_hex(&self.world.identity().xonly), Some("your inherited public key (BIP-340 x-only)"), None, false);
            if self.signature.is_none() && button(ui, "Sign with your key", Kind::Primary).clicked() {
                act = Some(0);
            }
            if let Some((sig, ok)) = &self.signature {
                hex_box(ui, sig, Some("signature (verifies against your public key, forever)"), Some(GREEN), false);
                note(ui, if *ok { "Valid. Every node in Cryptopolis can check this against your public key and the Archive hash." } else { "invalid" });
                ui.horizontal_wrapped(|ui| {
                    if !host.solved() && button(ui, "Broadcast to all nodes", Kind::Primary).clicked() {
                        act = Some(1);
                    }
                    if button(ui, "Save signed certificate", Kind::Normal).clicked() {
                        act = Some(2);
                    }
                });
            }
        });
        match act {
            Some(0) => self.sign(host),
            Some(1) => self.broadcast(host),
            Some(2) => {
                if let Some(cert) = self.certificate() {
                    let name = format!("cypherpunk-legacy-{}.txt", self.world.handle());
                    ui.ctx().copy_text(cert.clone());
                    host.download(name, cert);
                    host.sfx("confirm");
                }
            }
            _ => {}
        }
    }

    fn autoplay(&mut self, host: &mut Host) {
        self.sign(host);
        self.broadcast(host);
    }
}
