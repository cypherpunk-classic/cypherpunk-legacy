export function textWidth(text: string, spacing = 1): number {
  return text.length === 0 ? 0 : text.length * (3 + spacing) - spacing;
}

export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, spacing = 1): void {
  ctx.fillStyle = color;
  let cx = x;
  for (const raw of text.toUpperCase()) {
    const glyph = G[raw] ?? G['?']!;
    const rows = glyph.split('|');
    rows.forEach((row, ry) => {
      for (let rx = 0; rx < 3; rx++) if (row[rx] === '#') ctx.fillRect(cx + rx, y + ry, 1, 1);
    });
    cx += 3 + spacing;
  }
}
