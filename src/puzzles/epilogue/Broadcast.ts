import { sign, sigHex, verify } from '../../crypto/bip340';
import { sha256Hex } from '../../crypto/aead';
import { toHex, utf8 } from '../../crypto/bytes';
import { randomBytes } from '@noble/hashes/utils.js';
import { h } from '../../ui/dom';
import { btn, card, hexBox, lede, note, shorten } from '../../ui/widgets';
import type { Puzzle, PuzzleHost } from '../../ui/terminal';
import { identity } from '../../story/world';
import { state } from '../../core/state';

const MANIFESTO = `Privacy is necessary for an open society in the electronic age. Privacy is not secrecy. A private matter is something one doesn't want the whole world to know, but a secret matter is something one doesn't want anybody to know. Privacy is the power to selectively reveal oneself to the world.

We cannot expect governments, corporations, or other large, faceless organizations to grant us privacy out of their beneficence. We must defend our own privacy if we expect to have any.

Cypherpunks write code. We know that someone has to write software to defend privacy, and we're going to write it.`;

/**
 * Epilogue. The Archive, once public and signed, cannot be un-published. You
 * sign a release statement with your inherited key (BIP-340), bind it to the
 * Archive's hash, and broadcast it to every node in Cryptopolis. Warden's whole
 * power was keeping things locked; a signature everyone can verify ends it.
 */
export class Broadcast implements Puzzle {
  id = 'end.broadcast';
  title = 'LEGACY BROADCAST';
  subtitle = 'sign · bind · publish';
  accent = '#3ef0ff';
  closable = false as const;
  private host!: PuzzleHost;
  private archiveHash = '';
  private statement = '';
  private sigHexStr = '';
  private signed = false;
  private box!: HTMLElement;

  mount(host: PuzzleHost): void {
    this.host = host;
    this.archiveHash = sha256Hex(utf8(MANIFESTO + '|archive|' + state.data.seed));
    this.statement = `CYPHERPUNK LEGACY — PUBLIC RELEASE\nReleased by: ${state.data.handle}\nArchive SHA-256: ${this.archiveHash}\n\n${MANIFESTO}`;
    this.box = h('div');
    host.body.append(
      h(
        'div',
        { class: 'stack' },
        lede(
          'This is the last key you will turn tonight. The Archive is open; the Directorate wants it sealed again. But a signed, published document cannot be recalled. Sign your grandfather\'s manifesto with the key he left you, bind it to the Archive, and broadcast it to every node. After that, it is everyone\'s.',
        ),
        card('Release statement', h('div', { class: 'hex', style: 'white-space:pre-wrap;font-size:12px;max-height:200px;overflow:auto' }, this.statement)),
        card('Sign and broadcast', hexBox(toHex(identity().xonly), { label: 'your inherited public key (BIP-340 x-only)' }), h('div', { class: 'row', style: 'margin-top:10px' }, btn('Sign with your key', () => this.sign(), 'primary', 'broadcast-sign')), h('div', { style: 'margin-top:8px' }, this.box)),
      ),
    );
    host.status('Sign the release.', 'info');
  }

  private sign(): void {
    if (this.signed) return;
    const sig = sign(utf8(this.statement), identity().x, randomBytes(32));
    this.sigHexStr = sigHex(sig);
    const ok = verify(sig, utf8(this.statement), identity().xonly);
    this.signed = true;
    this.box.replaceChildren(
      hexBox(this.sigHexStr, { label: 'signature (verifies against your public key, forever)', tone: 'green' }),
      note(ok ? 'Valid. Every node in Cryptopolis can check this against your public key and the Archive hash.' : 'invalid'),
      h('div', { class: 'row', style: 'margin-top:10px' }, btn('Broadcast to all nodes', () => this.broadcast(), 'primary', 'broadcast-send'), btn('Download signed certificate', () => this.download())),
    );
    this.host.sfx('confirm');
    this.host.status('Signed. Now broadcast it.', 'ok');
  }

  private broadcast(): void {
    if (this.host.solved()) return;
    this.host.sfx('success');
    this.host.solve('Broadcast complete. The manifesto and the Archive are public, signed, and permanent. There is no key that locks this again.');
  }

  private download(): void {
    const cert = `${this.statement}\n\n---\nSIGNATURE (BIP-340 Schnorr, secp256k1):\n${this.sigHexStr}\n\nPUBLIC KEY (x-only): ${toHex(identity().xonly)}\n\nVerify: this signature is valid for the message above under the public key, forever.\nGenerated by Cypherpunk Legacy.`;
    try {
      const blob = new Blob([cert], { type: 'text/plain' });
      const url = URL.createObjectURL(blob);
      const a = h('a', { href: url, download: `cypherpunk-legacy-${state.data.handle}.txt` });
      document.body.append(a);
      a.click();
      a.remove();
      setTimeout(() => URL.revokeObjectURL(url), 1000);
      this.host.sfx('confirm');
    } catch {
      /* ignore */
    }
  }

  async autoplay(): Promise<void> {
    this.sign();
    this.broadcast();
  }
}

export { shorten };
