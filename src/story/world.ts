export function signAs(secret: bigint, msg: string): Sig {
  return sign(utf8(msg), secret);
}

export const hex32 = (x: bigint): string => toHex(fromHex(mod(x, N).toString(16).padStart(64, '0')));

/** Keyring details, shown in the menu. */
export function registerKeyringDetails(): void {
  registerItemDetails('letter', () => {
    const g = grandpa().mnemonic;
    return [['words', g.words.map((w, i) => (i === g.missingIndex && !state.flag('pro.seed') ? `${w[0]}▒▒▒` : w)).join(' ')]];
  });
  registerItemDetails('descriptor', () => [['descriptor', grandpa().descriptor]]);
  registerItemDetails('gateway-key', () => [
    ['path', BIP86_FIRST],
    ['x-only key', toHex(xOnly(grandpa().P))],
  ]);
  for (const i of [1, 2, 3, 4]) {
    registerItemDetails(`share${i}`, () => {
      const s = i === 3 ? vault().forged3 : vault().shares[i - 1]!;
      return [
        ['x', s.x.toString()],
        ['y', hex32(s.y)],
      ];
    });
  }
  registerItemDetails('vault-key', () => [['public key', toHex(xOnly(vault().V))]]);
  registerItemDetails('identity', () => [['x-only key', toHex(identity().xonly)]]);
  registerItemDetails('warden-key', () => [['public key', toHex(warden().P)]]);
}
