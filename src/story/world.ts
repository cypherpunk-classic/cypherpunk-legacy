/**
 * Everything cryptographic about *this* playthrough, derived from the save's
 * seed: Grandpa's mnemonic, the Vault key and its shares, Warden's leaky
 * signatures, Grandpa's Taproot address... Values are computed on first use
 * and cached for the session.
 */

const cache = new Map<string, unknown>();
let cachedSeed = '';

function memo<T>(key: string, fn: () => T): T {
  if (cachedSeed !== state.data.seed) {
    cache.clear();
    cachedSeed = state.data.seed;
  }
  if (!cache.has(key)) cache.set(key, fn());
  return cache.get(key) as T;
}

// ---------------------------------------------------------------- prologue

export interface GrandpaKeys {
  mnemonic: GrandpaSeed;
  seed: Bytes;
  key: DerivedKey;
  secret: bigint;
  P: Pt;
  descriptor: string;
}

export const grandpa = (): GrandpaKeys =>
  memo('grandpa', () => {
    const mnemonic = generateGrandpaSeed(state.rng('grandpa/mnemonic'));
    const seed = seedFromMnemonicSync(mnemonic.phrase);
    const key = deriveKey(seed, BIP86_FIRST);
    const secret = bytesToBigInt(key.privateKey);
    return { mnemonic, seed, key, secret, P: mul(secret), descriptor: descriptor(seed) };
  });

