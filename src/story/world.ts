export interface WardenWorld {
  d: bigint;
  P: Bytes;
  m1: string;
  m2: string;
  sig1: Sig;
  sig2: Sig;
}

export const warden = (): WardenWorld =>
  memo('warden', () => {
    const r = state.rng('warden');
    const d = evenKey(r.scalar(N));
    const k = r.scalar(N);
    const m1 = 'DLA ORDER 0417: SEAL THE ARCHIVE AT THE MINT. AUTH: WARDEN';
    const m2 = 'DLA ORDER 0418: DOUBLE THE CHECKPOINTS AT THE MASQUERADE. AUTH: WARDEN';
    return { d, P: xOnly(mul(d)), m1, m2, sig1: signWithNonce(utf8(m1), d, k), sig2: signWithNonce(utf8(m2), d, k) };
  });

export const custody = (): { d: bigint; P: Pt } =>
  memo('custody', () => {
    const d = state.rng('custody').scalar(N);
    return { d, P: mul(d) };
  });

export interface TaprootWorld {
  leaves: Leaf[];
  correct: [string, string];
  target: ReturnType<typeof tweakKey>;
}

export const LOCKTIME_2030 = 1893456000; // 2030-01-01T00:00:00Z

export const taproot = (): TaprootWorld =>
  memo('taproot', () => {
    const r = state.rng('taproot');
    const k = (): Bytes => xOnly(mul(r.scalar(N)));
    const mara = k();
    const juno = k();
    const felix = k();
    const leaves: Leaf[] = [
      leafTwoOfTwo('recovery', 'Recovery: Mara and Juno together', mara, 'mara', juno, 'juno'),
      leafTimelocked('heir', 'Inheritance: after 1 Jan 2030, the heir alone', LOCKTIME_2030, identity().xonly, 'heir'),
      leafSingleSig('escrow', 'Escrow: the Directorate alone', warden().P, 'warden'),
      leafTimelocked('felix', 'Fallback: after 1 Jan 2030, Felix alone', LOCKTIME_2030, felix, 'felix'),
    ];
    const root = tapBranchHash(tapLeafHash(leaves[0]!.script), tapLeafHash(leaves[1]!.script));
    return { leaves, correct: ['recovery', 'heir'], target: tweakKey(xOnly(grandpa().P), root) };
  });

